const STORAGE_KEY = "barberprime_locale";

function detectLocale() {
  var stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "pt" || stored === "en") return stored;
  return (navigator.language || "pt").startsWith("pt") ? "pt" : "en";
}

function applyTranslations(locale) {
  localStorage.setItem(STORAGE_KEY, locale);
  document.documentElement.lang = locale === "pt" ? "pt-BR" : "en";

  var tr = translations[locale];

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var val = tr[el.dataset.i18n];
    if (typeof val === "string") el.textContent = val;
  });

  document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
    var val = tr[el.dataset.i18nHtml];
    if (typeof val === "string") el.innerHTML = val;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
    var val = tr[el.dataset.i18nAria];
    if (typeof val === "string") el.setAttribute("aria-label", val);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
    var val = tr[el.dataset.i18nAlt];
    if (typeof val === "string") el.alt = val;
  });

  document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
    var val = tr[el.dataset.i18nTitle];
    if (typeof val === "string") el.title = val;
  });

  document.querySelectorAll("[data-i18n-iframe-title]").forEach(function (el) {
    var val = tr[el.dataset.i18nIframeTitle];
    if (typeof val === "string") el.setAttribute("title", val);
  });

  var btnPT = document.getElementById("langPT");
  var btnEN = document.getElementById("langEN");
  if (btnPT) btnPT.classList.toggle("lang-active", locale === "pt");
  if (btnEN) btnEN.classList.toggle("lang-active", locale === "en");
}

document.addEventListener("DOMContentLoaded", function () {
  var locale = detectLocale();
  applyTranslations(locale);

  var btnPT = document.getElementById("langPT");
  var btnEN = document.getElementById("langEN");
  if (btnPT) btnPT.addEventListener("click", function () { applyTranslations("pt"); });
  if (btnEN) btnEN.addEventListener("click", function () { applyTranslations("en"); });
});
